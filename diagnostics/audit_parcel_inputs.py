"""Read-only DB audit; writes reports only. Does not validate yield accuracy."""
import argparse
from datetime import datetime, timezone
import json
from pathlib import Path

import numpy as np
import pandas as pd

from db.connection import get_connection
from ml.scenarios.features import SCENARIO_FEATURE_COLUMNS
from ml.scenarios.scenario_service import (
    get_model_artifact, calculate_recent_yield, load_county_soil,
)
from ml.scenarios.weather_scenarios import create_weather_scenarios
from archive.ml.train.train_scenario_xgboost import load_dataset

SOIL = ['soil_ph', 'soil_soc_g_kg', 'soil_clay_pct']
NUMERIC = [c for c in SCENARIO_FEATURE_COLUMNS if c != 'crop']


def read_parcels():
    connection = get_connection()
    try:
        with connection.cursor() as cursor:
            cursor.execute('SET TRANSACTION READ ONLY')
            cursor.execute('''
                SELECT p.id, p.name, p.official_area_ha,
                       s.source, s.soil_ph, s.soil_soc_g_kg, s.soil_clay_pct,
                       s.measured_at,
                       (SELECT COUNT(*) FROM processed.county_boundary cb
                        WHERE ST_Covers(cb.geometry, ST_PointOnSurface(p.geometry))) AS county_matches,
                       (SELECT MIN(cb.county_name) FROM processed.county_boundary cb
                        WHERE ST_Covers(cb.geometry, ST_PointOnSurface(p.geometry))) AS county_name
                FROM app.parcel p
                LEFT JOIN LATERAL (
                    SELECT source, soil_ph, soil_soc_g_kg, soil_clay_pct, measured_at
                    FROM app.parcel_soil
                    WHERE parcel_id = p.id
                    ORDER BY CASE WHEN source = 'user' THEN 1
                                  WHEN source = 'soilgrids' THEN 2 END,
                             measured_at DESC NULLS LAST, created_at DESC
                    LIMIT 1
                ) s ON TRUE
                WHERE p.is_active = TRUE
                ORDER BY p.id
            ''')
            return pd.DataFrame(cursor.fetchall(), columns=[d.name for d in cursor.description])
    finally:
        connection.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--target-season-year', type=int, required=True)
    args = parser.parse_args()
    artifact = get_model_artifact()
    if artifact['feature_columns'] != list(SCENARIO_FEATURE_COLUMNS):
        raise ValueError('Artifact feature order does not match application.')
    training = load_dataset()
    if training.empty or not np.isfinite(training[NUMERIC].to_numpy(float)).all():
        raise ValueError('Empty or non-finite training reference.')
    # Current DB is a reference, not necessarily the exact original training snapshot.
    profiles = training[SOIL].drop_duplicates().to_numpy(float)
    scale = np.ptp(profiles, axis=0)
    scale[scale == 0] = 1.0
    parcels = read_parcels()
    if parcels.empty:
        raise ValueError('No active parcels found.')
    issues, ranges, changes, distances = [], [], [], []
    for parcel in parcels.to_dict('records'):
        pid = int(parcel['id'])
        try:
            if int(parcel['county_matches']) != 1:
                raise ValueError('Point-based county assignment is missing or ambiguous.')
            if parcel['source'] not in ('user', 'soilgrids'):
                raise ValueError('No supported saved soil source; no soil is generated by this audit.')
            soil = {c: float(parcel[c]) for c in SOIL}
            values = np.array([soil[c] for c in SOIL])
            area = float(parcel['official_area_ha'])
            if not np.isfinite(values).all() or not np.isfinite(area) or area <= 0:
                raise ValueError('Non-finite soil/area or non-positive area.')
            if not (0 <= values[0] <= 14 and 0 <= values[1] <= 1000 and 0 <= values[2] <= 100):
                raise ValueError('Soil violates physical unit bounds.')
            distance = float(np.sqrt(np.mean(((profiles - values) / scale) ** 2, axis=1)).min())
            distances.append({'parcel_id': pid, 'soil_source': parcel['source'],
                              'nearest_soil_distance': distance, **soil})
        except (ValueError, TypeError) as error:
            issues.append({'parcel_id': pid, 'crop': None, 'issue': str(error)})
            continue
        county = parcel['county_name']
        for crop in ['barley', 'maize', 'wheat']:
            try:
                reference = training.loc[training['crop'] == crop, NUMERIC]
                if reference.empty:
                    raise ValueError('Crop missing from training reference.')
                lower, upper = reference.min(), reference.max()
                recent, years = calculate_recent_yield(county, crop, args.target_season_year)
                weather = create_weather_scenarios(county, crop, args.target_season_year)
                county_soil = load_county_soil(county)
                for scenario, w in weather.items():
                    row = {'crop': crop, **soil,
                           'season_temperature_c': w['temperature_c'],
                           'season_precipitation_mm': w['precipitation_mm'],
                           'recent_yield_mean_t_ha': recent}
                    alternative = {**row, **county_soil}
                    inputs = pd.DataFrame([row, alternative])[SCENARIO_FEATURE_COLUMNS]
                    if not np.isfinite(inputs[NUMERIC].to_numpy(float)).all():
                        raise ValueError('Non-finite scenario or county-reference input.')
                    predicted = np.asarray(artifact['model'].predict(inputs), dtype=float)
                    if predicted.shape != (2,) or not np.isfinite(predicted).all():
                        raise ValueError('Invalid model output.')
                    if (predicted < 0).any():
                        raise ValueError('Negative predicted yield.')
                    for feature in NUMERIC:
                        value = float(row[feature])
                        ranges.append({'parcel_id': pid, 'crop': crop, 'scenario': scenario,
                                       'feature': feature, 'value': value,
                                       'train_min': float(lower[feature]),
                                       'train_max': float(upper[feature]),
                                       'outside_range': bool(value < lower[feature] or value > upper[feature])})
                    changes.append({'parcel_id': pid, 'county_name': county, 'crop': crop,
                                    'scenario': scenario, 'soil_source': parcel['source'],
                                    'season_start_year': args.target_season_year,
                                    'yield_year': args.target_season_year + (crop != 'maize'),
                                    'recent_yield_years': ','.join(map(str, years)),
                                    'parcel_soil_prediction': float(predicted[0]),
                                    'county_soil_prediction': float(predicted[1]),
                                    'soil_replacement_difference': float(predicted[0] - predicted[1])})
            except (ValueError, TypeError) as error:
                issues.append({'parcel_id': pid, 'crop': crop, 'issue': str(error)})
    directory = Path(__file__).resolve().parent / 'results' / datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
    directory.mkdir(parents=True, exist_ok=False)
    frames = {'input_ranges': pd.DataFrame(ranges), 'soil_replacement': pd.DataFrame(changes),
              'soil_distance': pd.DataFrame(distances),
              'issues': pd.DataFrame(issues, columns=['parcel_id', 'crop', 'issue'])}
    for name, frame in frames.items():
        frame.to_csv(directory / f'{name}.csv', index=False)
    settings = {'model_version': artifact.get('version'), 'model_variant': artifact.get('model_variant'),
                'training_data_sha256_from_artifact': artifact.get('training_data_sha256'),
                'target_season_start_year': args.target_season_year,
                'active_parcels': len(parcels), 'training_soil_profiles_in_current_db': len(profiles),
                'reference': 'Current DB training data; not fingerprint-verified against artifact.',
                'purpose': 'Input support and model behaviour audit; NOT parcel yield accuracy.'}
    (directory / 'settings.json').write_text(json.dumps(settings, indent=2), encoding='utf-8')
    print(json.dumps(settings, indent=2))
    print(f'\nCompleted scenario comparisons: {len(changes)}; issues: {len(issues)}')
    if ranges:
        print('\nOUTSIDE CROP TRAINING RANGE (scenario rows, not independent observations)')
        print(frames['input_ranges'].groupby(['crop', 'feature'])['outside_range'].agg(['sum', 'count']).to_string())
    if changes:
        report = frames['soil_replacement'].copy()
        report['absolute_difference'] = report['soil_replacement_difference'].abs()
        print('\n10 LARGEST CHANGES AFTER REPLACING PARCEL SOIL WITH COUNTY SOIL')
        print(report.nlargest(10, 'absolute_difference').to_string(index=False, float_format='%.3f'))
    if issues:
        print('\nISSUES\n' + frames['issues'].to_string(index=False))
    print(f'\nReports: {directory}')
    print('Inside individual ranges does not establish joint input familiarity.')
    print('Soil distance is descriptive; there is no calibrated acceptance threshold.')
    print('Prediction differences are neither accuracy gains nor causal soil effects.')
    print('All three crops are hypothetical cases for each active parcel.')
    print('No DB records, models or application settings were modified.')


if __name__ == '__main__':
    main()
